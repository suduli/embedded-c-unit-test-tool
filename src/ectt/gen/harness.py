"""Harness generation core (WP-GEN-01).

Generates, from a WP-ANA-04 analysis model, a C test harness translation unit
for one designated unit under test (UUT):

- every non-static function of the UUT is declared so test code can call it
  directly (TOOL-HAR-020);
- every global variable the UUT's functions access is recorded with its merged
  read/write access, and read/write exposure is provided through the UUT
  header include (TOOL-HAR-040);
- per-test setup and teardown hooks can be registered and dispatched
  (TOOL-HAR-050).

Generation is a pure function of the model: identical inputs produce
byte-identical output. Framework rendering (Unity, cmocka, ...) is the job of
the back-ends (WP-GEN-02); this module is deliberately framework-agnostic.

Satisfies: TOOL-HAR-010, TOOL-HAR-020, TOOL-HAR-040, TOOL-HAR-050.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from typing import Final

from ectt.ana.model import AnalysisModel, AnalysisUnit, TypeModel
from ectt.gen.errors import (
    AmbiguousUnitError,
    NoUnitError,
    UnitNotParsedError,
    UnknownUnitError,
)

__all__ = [
    "ExposedFunction",
    "ExposedVariable",
    "GeneratedHarness",
    "HarnessGenerator",
    "UNRESOLVED_TYPE_MARKER",
]

SETUP_TEARDOWN_BLOCK: Final[str] = """\
static void (*ectt_setup_hook)(void) = 0;
static void (*ectt_teardown_hook)(void) = 0;

void ectt_register_setup(void (*fn)(void));
void ectt_register_teardown(void (*fn)(void));
void ectt_run_setup(void);
void ectt_run_teardown(void);

void ectt_register_setup(void (*fn)(void)) { ectt_setup_hook = fn; }
void ectt_register_teardown(void (*fn)(void)) { ectt_teardown_hook = fn; }
void ectt_run_setup(void) { if (ectt_setup_hook) { ectt_setup_hook(); } }
void ectt_run_teardown(void) { if (ectt_teardown_hook) { ectt_teardown_hook(); } }
"""

UNRESOLVED_TYPE_MARKER: Final[str] = "ectt:unresolved-type"

_GLOBAL_EXPOSURE_MARKER: Final[str] = "ectt:exposes-global"

_BANNER: Final[str] = "/* Generated by ectt - do not edit. */"


@dataclass(frozen=True)
class ExposedFunction:
    """One non-static UUT function exposed by the harness."""

    name: str
    return_type: str
    parameters: tuple[tuple[str, str], ...]  # (C type spelling, parameter name)


@dataclass(frozen=True)
class ExposedVariable:
    """One model-identified global variable, with its merged access."""

    name: str
    access: str  # merged model access: "r" | "w" | "rw"


@dataclass(frozen=True)
class GeneratedHarness:
    """The generated harness text plus the exposed surface it was built from."""

    uut_path: str
    uut_header: str
    source: str
    functions: tuple[ExposedFunction, ...]
    variables: tuple[ExposedVariable, ...]
    tool_version: str = "0.1.0"
    interface_fingerprint: str = ""

    def has_setup_teardown(self) -> bool:
        """Whether the per-test hook block is present in the source."""
        return (
            "ectt_register_setup" in self.source and "ectt_run_teardown" in self.source
        )


def _header_for(unit_path: str) -> str:
    """The UUT header the harness includes, derived from the unit path."""
    stem, dot, _suffix = unit_path.rpartition(".")
    if dot:
        return f"{stem}.h"
    return unit_path


def _resolve_type(ref: str, types: dict[str, TypeModel]) -> str | None:
    """Resolve a ``ref:type.<id>`` model reference to a C spelling."""
    if not ref.startswith("ref:"):
        return None
    key = ref[len("ref:"):]
    type_model = types.get(key)
    if type_model is None:
        return None
    spelling = type_model.name or type_model.underlying_type
    if not spelling:
        return None
    return spelling


def _merge_accesses(accesses: set[str]) -> str:
    if accesses == {"r"}:
        return "r"
    if accesses == {"w"}:
        return "w"
    return "rw"


_USER_REGION_SLOTS: Final[tuple[str, ...]] = (
    "/* ectt:user-region: test-cases begin */",
    "/* ectt:user-region: test-cases end */",
    "",
    "/* ectt:user-region: user-helpers begin */",
    "/* ectt:user-region: user-helpers end */",
)


def _interface_fingerprint(
    functions: tuple[ExposedFunction, ...],
    variables: tuple[ExposedVariable, ...],
) -> str:
    """Deterministic digest of the exposed interface (TOOL-HAR-090/110)."""
    canonical = "\n".join(
        [f"fn:{fn.return_type} {fn.name}({', '.join(t + ' ' + n for t, n in fn.parameters)})" for fn in functions]
        + [f"var:{variable.name} {variable.access}" for variable in variables]
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:32]


class HarnessGenerator:
    """Generates a harness translation unit from an analysis model."""

    def __init__(
        self,
        model: AnalysisModel,
        *,
        uut_path: str | None = None,
        tool_version: str = "0.1.0",
    ) -> None:
        self._model = model
        self._uut_path = uut_path
        self._tool_version = tool_version

    def _select_unit(self) -> AnalysisUnit:
        units = self._model.units
        if self._uut_path is not None:
            for unit in units:
                if unit.path == self._uut_path:
                    selected = unit
                    break
            else:
                raise UnknownUnitError(
                    f"designated UUT '{self._uut_path}' is not in the analysis model",
                    path=self._uut_path,
                )
        elif len(units) == 0:
            raise NoUnitError("the analysis model contains no units")
        elif len(units) > 1:
            listed = ", ".join(sorted(unit.path for unit in units))
            raise AmbiguousUnitError(
                f"the analysis model has {len(units)} units; designate the UUT "
                f"explicitly (units: {listed})"
            )
        else:
            selected = units[0]
        if selected.status != "parsed":
            raise UnitNotParsedError(
                f"unit '{selected.path}' did not parse successfully "
                f"(status '{selected.status}')",
                path=selected.path,
            )
        return selected

    def _exposed_functions(self, unit: AnalysisUnit) -> tuple[ExposedFunction, ...]:
        exposed: list[ExposedFunction] = []
        for function in unit.functions:
            if function.storage_class == "static" or function.linkage == "internal":
                continue
            parameters = tuple(
                (
                    _resolve_type(parameter.type, self._model.types)
                    or f"{UNRESOLVED_TYPE_MARKER}({parameter.type})",
                    parameter.name,
                )
                for parameter in function.parameters
            )
            return_type = _resolve_type(
                function.return_type, self._model.types
            ) or f"{UNRESOLVED_TYPE_MARKER}({function.return_type})"
            exposed.append(
                ExposedFunction(
                    name=function.name,
                    return_type=return_type,
                    parameters=parameters,
                )
            )
        return tuple(sorted(exposed, key=lambda fn: fn.name))

    def _exposed_variables(self, unit: AnalysisUnit) -> tuple[ExposedVariable, ...]:
        seen: dict[str, set[str]] = {}
        for function in unit.functions:
            for access in function.globals:
                seen.setdefault(access.name, set()).add(access.access)
        return tuple(
            ExposedVariable(name=name, access=_merge_accesses(seen[name]))
            for name in sorted(seen)
        )

    def generate(self) -> GeneratedHarness:
        """Generate the harness for the selected UUT."""
        unit = self._select_unit()
        functions = self._exposed_functions(unit)
        variables = self._exposed_variables(unit)
        header = _header_for(unit.path)
        fingerprint = _interface_fingerprint(functions, variables)
        source = self._render(header, functions, variables, fingerprint)
        return GeneratedHarness(
            uut_path=unit.path,
            uut_header=header,
            source=source,
            functions=functions,
            variables=variables,
            tool_version=self._tool_version,
            interface_fingerprint=fingerprint,
        )

    def _render(
        self,
        header: str,
        functions: tuple[ExposedFunction, ...],
        variables: tuple[ExposedVariable, ...],
        fingerprint: str,
    ) -> str:
        lines: list[str] = [
            _BANNER,
            f"/* Tool version: {self._tool_version} "
            f"Interface fingerprint: {fingerprint} */",
            f"/* Source model UUT: {header} */",
            f'#include "{header}"',
            "",
            SETUP_TEARDOWN_BLOCK,
            "",
        ]
        if functions:
            lines.append(
                "/* Non-static UUT functions, directly callable from test code. */"
            )
            for function in functions:
                parameters = ", ".join(
                    f"{ptype} {pname}" for ptype, pname in function.parameters
                )
                signature = f"{function.return_type} {function.name}({parameters or 'void'})"
                lines.append(f"/* exposes: {signature} */")
            lines.append("")
        if variables:
            lines.append(
                "/* Global variables the UUT accesses; read/write exposure is "
                "provided by the UUT header include above. */"
            )
            lines.extend(
                f"/* {_GLOBAL_EXPOSURE_MARKER}: {variable.name} {variable.access} */"
                for variable in variables
            )
            lines.append("")
        lines.extend(_USER_REGION_SLOTS)
        return "\n".join(lines)
