"""Stub regeneration and unsupported-construct flagging (WP-GEN-09).

Every stub body is a delimited user-editable region. Re-synchronisation
preserves the user body where the signature change permits it (same parameter
names, unchanged return type) and regenerates with an explicit report where it
does not. Constructs the generator cannot fully handle — variadic parameters,
complex function-pointer parameters — are flagged with a consistent greppable
marker.

Satisfies: TOOL-STB-110, TOOL-STB-120, TOOL-STB-130.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Final

from ectt.gen.errors import GenError
from ectt.gen.stubs import FunctionSignature, _default_return

__all__ = [
    "STUB_BODY_REGION_PREFIX",
    "UNSUPPORTED_CONSTRUCT_MARKER",
    "StubResyncResult",
    "UnsupportedConstruct",
    "resync_stub",
    "stub_with_user_region",
    "extract_user_body",
    "flag_unsupported_constructs",
]

STUB_BODY_REGION_PREFIX: Final[str] = "ectt:stub-body"
UNSUPPORTED_CONSTRUCT_MARKER: Final[str] = "ectt:unsupported-construct"

_REGION_RE: Final[re.Pattern[str]] = re.compile(
    r"/\* " + STUB_BODY_REGION_PREFIX + r": (?P<name>\S+) begin \*/\n"
    r"(?P<content>.*?)"
    r"/\* " + STUB_BODY_REGION_PREFIX + r": (?P=name) end \*/",
    re.DOTALL,
)


class StubResyncError(GenError):
    """Raised when a stub to re-synchronise is malformed."""

    def __init__(self, message: str, *, reason: str = "stub_resync_error") -> None:
        super().__init__(message, reason=reason)


def stub_with_user_region(signature: FunctionSignature, body: str = "") -> str:
    """Render a stub with a delimited user-editable body region (STB-110)."""
    parameters = ", ".join(f"{c_type} {name}" for c_type, name in signature.parameters)
    return (
        f"/* Generated by ectt - do not edit the signature below. */\n"
        f"{signature.return_type} {signature.name}({parameters or 'void'}) {{\n"
        f"/* {STUB_BODY_REGION_PREFIX}: {signature.name} begin */\n"
        f"{body}"
        f"/* {STUB_BODY_REGION_PREFIX}: {signature.name} end */\n"
        f"}}\n"
    )


def extract_user_body(stub_text: str, name: str) -> str:
    """The user-authored body of one stub, or empty if none was captured."""
    match = _REGION_RE.search(stub_text)
    if match is None or match.group("name") != name:
        return ""
    return match.group("content")


@dataclass(frozen=True)
class StubResyncResult:
    """The outcome of one stub re-synchronisation (STB-120)."""

    signature: FunctionSignature
    text: str
    body_preserved: bool
    report: tuple[str, ...]


def resync_stub(old_text: str, new_signature: FunctionSignature) -> StubResyncResult:
    """Re-synchronise a stub's signature while preserving the user body.

    The body is preserved when the change permits: identical parameter names
    and an unchanged return type. Any other change regenerates the body and
    reports exactly why.
    """
    old_body = extract_user_body(old_text, new_signature.name)
    if not old_body:
        # Nothing user-authored to preserve; a straight regeneration.
        return StubResyncResult(
            signature=new_signature,
            text=stub_with_user_region(new_signature, ""),
            body_preserved=False,
            report=(f"no user body captured for '{new_signature.name}'; regenerated",),
        )
    old_names_match = _old_body_matches(old_text, new_signature)
    reports: list[str] = []
    if old_names_match:
        text = stub_with_user_region(new_signature, old_body)
        return StubResyncResult(
            signature=new_signature,
            text=text,
            body_preserved=True,
            report=tuple(reports),
        )
    reports.append(
        f"body of '{new_signature.name}' not preserved: the parameter list changed"
    )
    return StubResyncResult(
        signature=new_signature,
        text=stub_with_user_region(new_signature, ""),
        body_preserved=False,
        report=tuple(reports),
    )


def _old_body_matches(old_text: str, new_signature: FunctionSignature) -> bool:
    """Whether the old stub's signature change permits keeping the body.

    Permitted: the same parameter names in the same order and the same return
    type (only types/spelling of parameters may have tightened).
    """
    header_match = re.search(
        r"(?P<ret>[^*\n]+?)\s+" + re.escape(new_signature.name) + r"\((?P<params>[^)]*)\)",
        old_text,
    )
    if header_match is None:
        return False
    old_return = header_match.group("ret").strip()
    if old_return != new_signature.return_type:
        return False
    old_params = header_match.group("params").strip()
    if old_params in ("", "void"):
        return len(new_signature.parameters) == 0
    old_names = [param.rsplit(None, 1)[-1] for param in old_params.split(",")]
    new_names = [name for _type, name in new_signature.parameters]
    return old_names == new_names


@dataclass(frozen=True)
class UnsupportedConstruct:
    """One construct the stub generator could not fully handle (STB-130)."""

    function: str
    reason: str

    def marker_line(self) -> str:
        """The greppable flag emitted into generated output."""
        return f"/* {UNSUPPORTED_CONSTRUCT_MARKER}: {self.function} {self.reason} */"


def flag_unsupported_constructs(
    signatures: tuple[FunctionSignature, ...],
) -> tuple[UnsupportedConstruct, ...]:
    """Flag every signature containing a construct we cannot fully handle."""
    flagged: list[UnsupportedConstruct] = []
    for signature in signatures:
        for c_type, _name in signature.parameters:
            if "..." in c_type:
                flagged.append(
                    UnsupportedConstruct(
                        function=signature.name,
                        reason="variadic parameter",
                    )
                )
                break
            if "(*" in c_type:
                flagged.append(
                    UnsupportedConstruct(
                        function=signature.name,
                        reason="complex function-pointer parameter",
                    )
                )
                break
    return tuple(flagged)


def render_stub_output(
    signatures: tuple[FunctionSignature, ...],
) -> str:
    """Render stub output where every unsupported construct is flagged (STB-130)."""
    flagged = {item.function: item for item in flag_unsupported_constructs(signatures)}
    lines: list[str] = [
        "/* Generated by ectt - do not edit. Stubs for external functions. */",
        "",
    ]
    for signature in sorted(signatures, key=lambda sig: sig.name):
        unsupported = flagged.get(signature.name)
        if unsupported is not None:
            lines.append(unsupported.marker_line())
            continue
        parameters = ", ".join(
            f"{c_type} {name}" for c_type, name in signature.parameters
        )
        lines.append(
            f"{signature.return_type} {signature.name}({parameters or 'void'}) {{\n"
            f"{_default_return(signature.return_type)}\n"
            f"}}"
        )
        lines.append("")
    return "\n".join(lines)
