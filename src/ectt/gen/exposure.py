"""Static exposure and integration-scope harnesses (WP-GEN-03).

Static exposure is optional: with ``expose_statics`` the harness includes the
UUT source translation unit so test code can reach file-static functions, and
records each static prototype with a greppable marker. Integration harnesses
span two or more designated units, expose every member's non-static surface,
and mark exactly the callees defined by no member as the only stub
requirements.

Satisfies: TOOL-HAR-030, TOOL-HAR-080.
"""

from __future__ import annotations

from dataclasses import dataclass

from ectt.ana.model import AnalysisModel
from ectt.gen.errors import GenError
from ectt.gen.globals import resolve_global_exposures
from ectt.gen.harness import (
    ExposedFunction,
    GeneratedHarness,
    HarnessGenerator,
    _header_for,
)

__all__ = [
    "STATIC_EXPOSURE_MARKER",
    "STUB_REQUIRED_MARKER",
    "IntegrationScopeTooSmallError",
    "IntegrationHarness",
    "generate_integration_harness",
]

STATIC_EXPOSURE_MARKER = "ectt:exposes-static"
STUB_REQUIRED_MARKER = "ectt:stub-required"

_BANNER = "/* Generated by ectt - do not edit. Integration harness. */"


class IntegrationScopeTooSmallError(GenError):
    """Raised when an integration harness is requested for fewer than two units."""

    def __init__(self, message: str, *, reason: str = "integration_scope_too_small") -> None:
        super().__init__(message, reason=reason)


def generate_with_statics(
    model: AnalysisModel,
    *,
    uut_path: str | None = None,
    tool_version: str = "0.1.0",
) -> GeneratedHarness:
    """Generate a harness that optionally exposes UUT static functions.

    The harness includes the UUT ``.c`` translation unit (not just the
    header), which gives test code direct access to file-static functions;
    every static function carries a greppable exposure record with its
    prototype.
    """
    generator = HarnessGenerator(model, uut_path=uut_path, tool_version=tool_version)
    unit = generator._select_unit()
    functions = generator._exposed_functions(unit)
    variables = generator._exposed_variables(unit)
    del functions  # recomputed below with statics included
    statics = [
        function
        for function in unit.functions
        if function.storage_class == "static" or function.linkage == "internal"
    ]
    exposed = generator._exposed_functions(unit)
    header = _header_for(unit.path)
    lines: list[str] = [
        _BANNER.replace("Integration harness.", "Static-exposed harness."),
        f"/* Tool version: {tool_version} */",
        f"/* Source model UUT: {header} (static exposure) */",
        f'#include "{unit.path}"',
        "",
    ]
    from ectt.gen.harness import _resolve_type

    lines.extend(
        f"/* {STATIC_EXPOSURE_MARKER}: "
        + (
            _resolve_type(function.return_type, model.types)
            or f"ectt:unresolved-type({function.return_type})"
        )
        + f" {function.name}("
        + ", ".join(
            f"{_resolve_type(parameter.type, model.types) or parameter.type} {parameter.name}"
            for parameter in function.parameters
        )
        + ") */"
        for function in sorted(statics, key=lambda fn: fn.name)
    )
    lines.append("")
    lines.extend(
        f"/* exposes: {function.return_type} {function.name}("
        + (
            ", ".join(f"{ptype} {pname}" for ptype, pname in function.parameters)
            or "void"
        )
        + ") */"
        for function in exposed
    )
    # File-static variables are reachable here: the source include above makes
    # their definitions visible (TOOL-HAR-040, schema 1.5 inventory). The
    # record carries the resolved type; a variable whose type the model cannot
    # resolve is recorded as not reachable, never guessed.
    static_variable_records = [
        exposure.record()
        for exposure in resolve_global_exposures(unit, model.types)
        if exposure.mechanism == "source-inclusion"
    ]
    if static_variable_records:
        lines.append("/* File-static variables reached through this source include. */")
        lines.extend(static_variable_records)
        lines.append("")
    source = "\n".join(lines) + "\n"
    from ectt.gen.harness import _interface_fingerprint

    return GeneratedHarness(
        uut_path=unit.path,
        uut_header=header,
        source=source,
        functions=exposed,
        variables=variables,
        tool_version=tool_version,
        interface_fingerprint=_interface_fingerprint(exposed, variables),
    )


@dataclass(frozen=True)
class IntegrationHarness:
    """The integration harness text and its per-member exposed surfaces."""

    members: tuple[str, ...]
    functions: tuple[ExposedFunction, ...]
    stub_required: tuple[str, ...]
    source: str


def generate_integration_harness(
    model: AnalysisModel,
    uut_paths: tuple[str, ...],
    *,
    calls: dict[str, tuple[str, ...]] | None = None,
    defined_functions: dict[str, tuple[str, ...] | set[str]] | None = None,
    tool_version: str = "0.1.0",
) -> IntegrationHarness:
    """Generate a harness spanning two or more units (TOOL-HAR-080).

    Every member header is included and every member's non-static functions
    are exposed. When callee references and member-defined functions are
    supplied, the callees defined by no member are marked as the only stub
    requirements; intra-set calls are never marked.
    """
    if len(uut_paths) < 2:
        raise IntegrationScopeTooSmallError(
            f"an integration harness needs two or more units, got {len(uut_paths)}"
        )
    known_paths = {unit.path for unit in model.units}
    members: list[str] = []
    exposed: list[ExposedFunction] = []
    for path in uut_paths:
        if path not in known_paths:
            from ectt.gen.errors import UnknownUnitError

            raise UnknownUnitError(
                f"integration member '{path}' is not in the analysis model",
                path=path,
            )
        generator = HarnessGenerator(model, uut_path=path, tool_version=tool_version)
        harness = generator.generate()
        members.append(harness.uut_header)
        exposed.extend(harness.functions)
    exposed.sort(key=lambda fn: (fn.name, fn.return_type))
    stub_required: list[str] = []
    if calls is not None and defined_functions is not None:
        from ectt.ing.conflicts import stub_requirements

        stub_required = [
            requirement.symbol
            for requirement in stub_requirements(calls, defined_functions)
        ]
    lines: list[str] = [
        _BANNER,
        f"/* Tool version: {tool_version} */",
        f"/* Integration members: {', '.join(members)} */",
        "",
    ]
    lines.extend(f'#include "{member}"' for member in members)
    lines.append("")
    lines.extend(
        f"/* exposes: {function.return_type} {function.name}("
        + (
            ", ".join(f"{ptype} {pname}" for ptype, pname in function.parameters)
            or "void"
        )
        + ") */"
        for function in exposed
    )
    if stub_required:
        lines.append("")
        lines.append(
            "/* Dependencies external to the selected set; the only stubs needed. */"
        )
        lines.extend(f"/* {STUB_REQUIRED_MARKER}: {symbol} */" for symbol in stub_required)
    return IntegrationHarness(
        members=tuple(members),
        functions=tuple(exposed),
        stub_required=tuple(stub_required),
        source="\n".join(lines) + "\n",
    )
