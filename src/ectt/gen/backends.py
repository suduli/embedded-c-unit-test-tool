"""Framework back-ends: Unity and cmocka (WP-GEN-02).

A back-end is a declarative descriptor: an id, the framework header the
generated file includes, and a template rendering the WP-GEN-01 harness
surface (exposed functions, setup/teardown hooks) into a framework-specific
C test file. Adding a framework means registering a descriptor — no tool
source change. Every render passes a C++-free scan so no back-end can
introduce a C++ compilation or runtime dependency.

Satisfies: TOOL-HAR-060, TOOL-HAR-070, TOOL-PLG-030.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from ectt.gen.errors import GenError
from ectt.gen.harness import GeneratedHarness
from ectt.gen.testbody import CaseSections

__all__ = [
    "UNITY_BACKEND_ID",
    "CMOCKA_BACKEND_ID",
    "FrameworkBackendError",
    "CppConstructInOutputError",
    "UnknownBackendError",
    "DuplicateBackendError",
    "FrameworkBackend",
    "BackendRegistry",
    "register_framework_builtins",
    "render_framework_test",
]

UNITY_BACKEND_ID = "unity"
CMOCKA_BACKEND_ID = "cmocka"

_CPP_PATTERNS = (
    "::",
    "template<",
    "class ",
    "catch",
    "new ",
    "delete ",
    "namespace ",
)


class FrameworkBackendError(GenError):
    """Base for framework back-end problems."""

    def __init__(
        self, message: str, *, reason: str = "framework_backend_error"
    ) -> None:
        super().__init__(message, reason=reason)


class CppConstructInOutputError(FrameworkBackendError):
    """Raised when a back-end render contains C++ constructs."""

    def __init__(
        self, message: str, *, reason: str = "cpp_construct_in_output"
    ) -> None:
        super().__init__(message, reason=reason)


class UnknownBackendError(FrameworkBackendError):
    """Raised when a back-end id is not registered."""

    def __init__(self, message: str, *, reason: str = "unknown_backend") -> None:
        super().__init__(message, reason=reason)


class DuplicateBackendError(FrameworkBackendError):
    """Raised when a back-end id is registered twice."""

    def __init__(self, message: str, *, reason: str = "duplicate_backend") -> None:
        super().__init__(message, reason=reason)


def _assert_no_cpp_constructs(text: str) -> None:
    for pattern in _CPP_PATTERNS:
        if pattern in text:
            raise CppConstructInOutputError(
                f"back-end output contains C++ construct '{pattern.strip()}'; "
                f"framework outputs must be C, never C++"
            )


@dataclass(frozen=True)
class FrameworkBackend:
    """One declarative framework back-end descriptor.

    ``cpp_allowed`` opts a back-end out of the C++-free output scan (the
    GoogleTest back-end renders C++); ``host_only`` marks a back-end that can
    never run on a target.
    """

    backend_id: str
    framework_header: str
    template: str
    cpp_allowed: bool = False
    host_only: bool = False

    def __post_init__(self) -> None:
        if not isinstance(self.backend_id, str) or not self.backend_id.strip():
            raise FrameworkBackendError("back-end id must be a non-empty string")
        if not isinstance(self.framework_header, str) or not self.framework_header.strip():
            raise FrameworkBackendError(
                f"back-end '{self.backend_id}' framework header must be a non-empty string"
            )
        if not isinstance(self.template, str) or "{uut_header}" not in self.template:
            raise FrameworkBackendError(
                f"back-end '{self.backend_id}' template must include the "
                f"{{uut_header}} slot"
            )
        if not isinstance(self.cpp_allowed, bool) or not isinstance(self.host_only, bool):
            raise FrameworkBackendError(
                f"back-end '{self.backend_id}' cpp_allowed/host_only must be booleans"
            )

    @classmethod
    def from_descriptor(cls, descriptor: Mapping[str, Any]) -> FrameworkBackend:
        """Build a descriptor from a declarative mapping (TOOL-PLG-030)."""
        for field_name in ("backend_id", "framework_header", "template"):
            if field_name not in descriptor:
                raise FrameworkBackendError(
                    f"back-end descriptor is missing '{field_name}'"
                )
        return cls(
            backend_id=str(descriptor["backend_id"]),
            framework_header=str(descriptor["framework_header"]),
            template=str(descriptor["template"]),
            cpp_allowed=bool(descriptor.get("cpp_allowed", False)),
            host_only=bool(descriptor.get("host_only", False)),
        )


_UNITY_TEMPLATE = """\
/* Generated by ectt - {backend_id} back-end. */
#include "{uut_header}"
#include "{framework_header}"
#include "ectt_harness.h"
{case_section}
void setUp(void)
{
{setup_hook}
}

void tearDown(void)
{
{teardown_hook}
}

{function_prototypes}

void run_all_tests(void)
{
{test_invocations}
}
"""

_CMOCKA_TEMPLATE = """\
/* Generated by ectt - {backend_id} back-end. */
#include "{uut_header}"
#include "{framework_header}"
#include "ectt_harness.h"
{case_section}
int setup(void **state)
{
{setup_hook}
    return 0;
}

int teardown(void **state)
{
{teardown_hook}
    return 0;
}

{function_prototypes}

const struct CMUnitTest ectt_tests[] = {
{test_invocations}
};
"""

_BUILTIN_DESCRIPTORS: tuple[dict[str, str], ...] = (
    {
        "backend_id": UNITY_BACKEND_ID,
        "framework_header": "unity.h",
        "template": _UNITY_TEMPLATE,
    },
    {
        "backend_id": CMOCKA_BACKEND_ID,
        "framework_header": "cmocka.h",
        "template": _CMOCKA_TEMPLATE,
    },
)


class BackendRegistry:
    """Public registry of framework back-end descriptors."""

    def __init__(self) -> None:
        self._backends: dict[str, FrameworkBackend] = {}

    def register_descriptor(self, descriptor: Mapping[str, Any]) -> FrameworkBackend:
        """Register a back-end from a declarative mapping."""
        backend = FrameworkBackend.from_descriptor(descriptor)
        if backend.backend_id in self._backends:
            raise DuplicateBackendError(
                f"back-end '{backend.backend_id}' is already registered"
            )
        self._backends[backend.backend_id] = backend
        return backend

    def register(self, backend: FrameworkBackend) -> None:
        """Register a descriptor object."""
        self.register_descriptor(
            {
                "backend_id": backend.backend_id,
                "framework_header": backend.framework_header,
                "template": backend.template,
            }
        )

    def lookup(self, backend_id: str) -> FrameworkBackend:
        """Return the descriptor registered under ``backend_id``."""
        try:
            return self._backends[backend_id]
        except KeyError:
            raise UnknownBackendError(
                f"no framework back-end is registered under '{backend_id}'"
            ) from None

    def list_ids(self) -> tuple[str, ...]:
        """Registered back-end ids, ordered deterministically."""
        return tuple(sorted(self._backends))


def register_framework_builtins(registry: BackendRegistry) -> None:
    """Register the Unity and cmocka built-ins through the descriptor path."""
    for descriptor in _BUILTIN_DESCRIPTORS:
        registry.register_descriptor(descriptor)


def render_framework_test(
    backend_id: str,
    harness: GeneratedHarness,
    registry: BackendRegistry,
    *,
    test_invocations: str = "",
    setup_hook: str = "",
    teardown_hook: str = "",
    test_cases: CaseSections | None = None,
) -> str:
    """Render the harness surface into the back-end's C test file.

    With ``test_cases`` (a ``ectt.gen.testbody.CaseSections``), the back-end
    emits the per-case functions — ``ectt_begin_test`` / ``ectt_end_test``
    markers, stub programming, expectation checks reported through
    ``ectt_fail`` — and the framework entry points run them. The
    ``{case_section}`` template slot carries the file-scope section; a
    template without the slot cannot host cases and is refused with a named
    error. Without ``test_cases`` the render is byte-identical to the
    slot-less history.
    """
    backend = registry.lookup(backend_id)
    case_text = ""
    if test_cases is not None:
        if "{case_section}" not in backend.template:
            raise FrameworkBackendError(
                f"back-end '{backend_id}' template has no {{case_section}} slot; "
                "it cannot host generated per-case functions",
                reason="missing_case_section_slot",
            )
        case_text = str(test_cases.case_section) + "\n"
        if test_invocations:
            raise FrameworkBackendError(
                "test_cases and test_invocations are mutually exclusive; "
                "the case section renders its own invocations",
                reason="conflicting_invocation_sources",
            )
        test_invocations = str(test_cases.test_invocations)
    prototypes = "\n".join(
        f"/* exposes: {function.return_type} {function.name}("
        + (
            ", ".join(f"{ptype} {pname}" for ptype, pname in function.parameters)
            or "void"
        )
        + ") */"
        for function in harness.functions
    )
    rendered = (
        backend.template.replace("{backend_id}", backend.backend_id)
        .replace("{uut_header}", harness.uut_header)
        .replace("{framework_header}", backend.framework_header)
        .replace("{case_section}\n", case_text)
        .replace("{function_prototypes}", prototypes)
        .replace("{setup_hook}", setup_hook)
        .replace("{teardown_hook}", teardown_hook)
        .replace("{test_invocations}", test_invocations)
    )
    if not backend.cpp_allowed:
        _assert_no_cpp_constructs(rendered)
    return rendered


_GTEST_TEMPLATE = """/* Generated by ectt - googletest back-end (host-only). */
#include "{uut_header}"
#include "{framework_header}"

namespace { /* host-only C++ output, allowed by descriptor */

{function_prototypes}

{test_invocations}

}  // namespace
"""

GTEST_BACKEND_ID = "googletest"


def register_gtest_backend(registry: BackendRegistry) -> FrameworkBackend:
    """Register the optional host-only GoogleTest back-end (TOOL-HAR-065).

    Deliberately NOT part of ``register_framework_builtins``: the back-end is
    optional and no documented workflow requires it.
    """
    return registry.register_descriptor(
        {
            "backend_id": GTEST_BACKEND_ID,
            "framework_header": "gtest/gtest.h",
            "template": _GTEST_TEMPLATE,
            "cpp_allowed": True,
            "host_only": True,
        }
    )
