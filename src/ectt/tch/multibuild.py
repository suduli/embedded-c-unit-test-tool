"""Multi-toolchain builds and reproducible container specifications (WP-TCH-05).

One plan builds the same suite for every named toolchain, each isolated in
its own build directory with per-toolchain commands. The reproducible
container specification is generated deterministically from supplied data —
a pinned base image with digest and the validated toolchain roster — as
version-controllable text; no digest is invented.

Satisfies: TOOL-TCH-080, TOOL-TCH-090.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

from ectt.tch.config import CompilerConfigRegistry
from ectt.tch.errors import TchError

if TYPE_CHECKING:
    from ectt.bld.crossbuild import CrossBuildPlan
    from ectt.bld.plan import ArtifactSpec

__all__ = [
    "DuplicateToolchainError",
    "ContainerSpecError",
    "MultiBuildPlan",
    "plan_multi_toolchain_builds",
    "container_spec",
]


class DuplicateToolchainError(TchError):
    """Raised when the same toolchain appears twice in one build plan."""

    def __init__(self, message: str, *, reason: str = "duplicate_toolchain") -> None:
        super().__init__(message, reason=reason)


class ContainerSpecError(TchError):
    """Raised when container specification data is missing or malformed."""

    def __init__(self, message: str, *, reason: str = "container_spec_error") -> None:
        super().__init__(message, reason=reason)


@dataclass(frozen=True)
class MultiBuildPlan:
    """One invocation building the suite for several isolated toolchains."""

    build_root: str
    plans: tuple[CrossBuildPlan, ...]

    def to_dict(self) -> dict[str, Any]:
        """Canonical, JSON-safe mapping (deterministic key order)."""
        return {
            "build_root": self.build_root,
            "plans": [plan.to_dict() for plan in self.plans],
        }


def plan_multi_toolchain_builds(
    toolchain_names: tuple[str, ...],
    specs: tuple[ArtifactSpec, ...],
    registry: CompilerConfigRegistry,
    *,
    build_root: str = "build",
    coverage_kinds: tuple[str, ...] = (),
) -> MultiBuildPlan:
    """Plan the same suite for every toolchain, in isolated directories.

    Each toolchain gets its own ``<root>/<toolchain>/`` build directory and
    per-toolchain commands; the whole thing is one plan (one invocation).
    """
    from ectt.bld.crossbuild import plan_cross_build

    seen: set[str] = set()
    for name in toolchain_names:
        if name in seen:
            raise DuplicateToolchainError(
                f"toolchain '{name}' appears twice in the build plan"
            )
        seen.add(name)
    plans: list[CrossBuildPlan] = []
    for name in sorted(seen):
        config = registry.lookup(name)  # UnknownCompilerConfigError when absent
        plan = plan_cross_build(
            specs,
            config,
            build_root=f"{build_root.rstrip('/')}/{name}",
            coverage_kinds=coverage_kinds,
        )
        plans.append(plan)
    return MultiBuildPlan(build_root=build_root, plans=tuple(plans))


def container_spec(
    toolchain_names: tuple[str, ...],
    *,
    base_image: str,
    base_image_digest: str,
    build_root: str = "/work",
) -> str:
    """Generate the reproducible container specification text (TCH-090).

    Deterministic, version-controllable text pinning the base image by digest
    and listing the validated toolchain roster. Digest data comes from the
    caller; nothing is invented.
    """
    if not base_image.strip():
        raise ContainerSpecError("container spec requires a base image name")
    if not base_image_digest.strip():
        raise ContainerSpecError(
            "container spec requires a pinned base image digest; "
            "reproducibility cannot be claimed without one"
        )
    ordered = sorted(dict.fromkeys(toolchain_names))
    if not ordered:
        raise ContainerSpecError("container spec requires at least one toolchain")
    lines: list[str] = [
        "# Generated by ectt - reproducible toolchain container (owner-review draft).",
        "# The image build runs in CI; this specification pins its inputs.",
        f"FROM {base_image}@{base_image_digest}",
        "",
        "# Validated toolchains shipped in this image:",
    ]
    lines.extend(f"#   - {name}" for name in ordered)
    lines.extend(
        [
            "",
            f"WORKDIR {build_root}",
            "# Toolchain validation runs at image build time; the digests above pin",
            "# every input so an independent rebuild obtains functionally identical",
            "# artifacts (TOOL-SEC-030).",
        ]
    )
    return "\n".join(lines) + "\n"
