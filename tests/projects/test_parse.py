"""Source parsing: the register is the only source, totals are derived,
and malformed input stops the import before any write is proposed."""
from __future__ import annotations

from pathlib import Path

import pytest

from conftest import make_plan, make_srs, write_fixture_repo

import github_projects as gp

REPO_ROOT = Path(__file__).resolve().parents[2]


def test_current_source_yields_191_unique_packages():
    """Baseline acceptance: exactly 191 unique work-package records."""
    packages = gp.load_source(REPO_ROOT)
    wids = [p.wid for p in packages]
    assert len(wids) == 191
    assert len(set(wids)) == 191


def test_derived_totals_match_the_register_audit():
    """PLAN-001 §7.2 is regenerated by plan_check; the importer must agree with it."""
    packages = gp.load_source(REPO_ROOT)
    totals = gp.totals(packages)
    assert totals["requirements_allocated"] == 336
    assert totals["dependency_edges"] == {"code": 275, "port-mediated": 2, "schedule-only": 10}
    assert totals["by_layer"] == {
        "Validation spikes": 3,
        "L0 — Platform and Persistence": 13,
        "L1 — Comprehension": 23,
        "L2 — Synthesis": 23,
        "L3 — Realization": 14,
        "L4 — Evidence": 32,
        "L5 — Interfaces": 30,
        "L6 — Assurance and Ecosystem": 53,
    }


def test_totals_are_derived_not_hardcoded():
    """The tool must derive counts from the source; '191' may not appear in it."""
    tool_source = (REPO_ROOT / "tools" / "github_projects.py").read_text(encoding="utf-8")
    assert "191" not in tool_source


def test_orphan_row_after_blank_line_is_still_parsed():
    """WP-REP-12 sits in its own table fragment after a blank line in §5.5."""
    packages = gp.load_source(REPO_ROOT)
    rep12 = next(p for p in packages if p.wid == "WP-REP-12")
    assert rep12.layer == "L4 — Evidence"
    assert rep12.reqs == ["MIG-060"]
    assert rep12.acceptance is not None


def test_spikes_map_to_the_validation_spikes_component():
    packages = gp.load_source(REPO_ROOT)
    spikes = [p for p in packages if p.wid.startswith("WP-SPIKE")]
    assert len(spikes) == 3
    assert all(p.component == "Validation spikes" for p in spikes)
    assert all(p.phase == "P0" and p.reqs == [] for p in spikes)


def test_dependency_annotations_preserved():
    packages = gp.load_source(REPO_ROOT)
    core05 = next(p for p in packages if p.wid == "WP-CORE-05")
    assert core05.deps == ["~ANA-04", "~GEN-01"]
    atg04 = next(p for p in packages if p.wid == "WP-ATG-04")
    assert "^COV-01" in atg04.deps
    prj01 = next(p for p in packages if p.wid == "WP-PRJ-01")
    assert prj01.deps == ["CORE-01"]


def test_exit_criteria_extracted_where_recorded():
    packages = gp.load_source(REPO_ROOT)
    with_criteria = {p.wid for p in packages if p.acceptance}
    assert "WP-CORE-01" in with_criteria
    assert "WP-REP-12" in with_criteria
    core01 = next(p for p in packages if p.wid == "WP-CORE-01")
    assert "byte-identical" in core01.acceptance
    assert sum(1 for p in packages if p.acceptance) == len(with_criteria)


def test_requirement_attributes_come_from_srs():
    packages = gp.load_source(REPO_ROOT)
    prj01 = next(p for p in packages if p.wid == "WP-PRJ-01")
    assert prj01.srs_attrs["PRJ-010"] == ("M", "P2", "I")
    assert prj01.srs_attrs["UIX-320"] == ("M", "P1", "I")


def _base_requirements() -> dict[str, tuple[str, str, str]]:
    return {"AAA-010": ("M", "P1", "T"), "BBB-020": ("S", "P2", "I")}


def _base_plan() -> dict[str, list[tuple]]:
    return {
        "Validation spikes": [],
        "L0 — Test": [
            ("WP-AAA-01", "First capability", "CMP-AAA", "P1", 2, "AAA-010", "—", False),
            ("WP-BBB-01", "Second capability", "CMP-BBB", "P2", 3, "BBB-020", "AAA-01", False),
        ],
    }


def test_malformed_row_stops_import(tmp_path):
    plan = make_plan(_base_plan())
    broken = plan.replace("| `WP-AAA-01` | First capability | CMP-AAA | P1 | 2w | AAA-010 | — |  |",
                          "| `WP-AAA-01` | First capability | CMP-AAA | P1 | 2w | AAA-010 |")
    root = write_fixture_repo(tmp_path, broken, make_srs(_base_requirements()))
    with pytest.raises(gp.ProjectsError, match="malformed work-package row"):
        gp.load_source(root)


def test_duplicate_package_id_stops_import(tmp_path):
    sections = _base_plan()
    sections["L0 — Test"].append(sections["L0 — Test"][0])
    sections["L0 — Test"][1] = ("WP-AAA-01", "First capability", "CMP-AAA", "P1", 2, "AAA-010", "—", False)
    root = write_fixture_repo(tmp_path, make_plan(sections), make_srs(_base_requirements()))
    with pytest.raises(gp.ProjectsError, match="duplicate work package WP-AAA-01"):
        gp.load_source(root)


