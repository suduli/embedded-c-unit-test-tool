"""Tests for the WP-GEN-01 harness generation core.

Covers: UUT selection and its named errors, exposure of every non-static
function, the global access record with merged read/write, per-test
setup/teardown hooks, and byte-identical regeneration.

Verifies: TOOL-HAR-010, TOOL-HAR-020, TOOL-HAR-040, TOOL-HAR-050.
"""

from __future__ import annotations

import pytest

from ectt.ana.model import (
    AnalysisModel,
    AnalysisUnit,
    FunctionModel,
    GlobalAccessModel,
    ParameterModel,
    ProvenanceModel,
    SourceLocation,
    TypeModel,
)
from ectt.gen import (
    AmbiguousUnitError,
    ExposedVariable,
    GeneratedHarness,
    HarnessGenerator,
    NoUnitError,
    UnitNotParsedError,
    UnknownUnitError,
)


def _builtin(name: str) -> TypeModel:
    return TypeModel(kind="builtin", name=name)


def _function(
    name: str,
    *,
    storage_class: str = "none",
    linkage: str = "external",
    parameters: tuple[ParameterModel, ...] = (),
    return_type: str = "ref:type.int",
    globals_: tuple[GlobalAccessModel, ...] = (),
) -> FunctionModel:
    return FunctionModel(
        name=name,
        linkage=linkage,
        storage_class=storage_class,
        location=SourceLocation(file="uut.c", line=1),
        return_type=return_type,
        parameters=parameters,
        globals=globals_,
    )


def _model(
    units: tuple[AnalysisUnit, ...],
    *,
    types: dict[str, TypeModel] | None = None,
) -> AnalysisModel:
    return AnalysisModel(
        provenance=ProvenanceModel(
            tool_version="0.1.0",
            front_end="fixture",
            generated_at="2026-11-18T00:00:00Z",
        ),
        units=units,
        types=types if types is not None else {"type.int": _builtin("int")},
    )


def _single_unit_model(
    functions: tuple[FunctionModel, ...],
    *,
    types: dict[str, TypeModel] | None = None,
    path: str = "uut.c",
    status: str = "parsed",
) -> AnalysisModel:
    return _model(
        (
            AnalysisUnit(
                path=path,
                status=status,
                functions=functions,
                types=types or {},
            ),
        ),
        types=types,
    )


def test_harness_generated_without_manual_editing() -> None:
    """verifies: TOOL-HAR-010"""
    model = _single_unit_model((_function("compute"),))
    harness = HarnessGenerator(model).generate()
    assert isinstance(harness, GeneratedHarness)
    assert harness.uut_path == "uut.c"
    assert harness.uut_header == "uut.h"
    assert '#include "uut.h"' in harness.source
    assert harness.source.startswith("/* Generated by ectt - do not edit. */")


def test_harness_header_derived_for_non_c_suffix() -> None:
    """verifies: TOOL-HAR-010"""
    model = _single_unit_model((_function("compute"),), path="driver.inc")
    harness = HarnessGenerator(model).generate()
    assert harness.uut_header == "driver.h"


def test_every_non_static_function_is_exposed() -> None:
    """verifies: TOOL-HAR-020"""
    model = _single_unit_model(
        (
            _function("alpha"),
            _function("beta"),
            _function("hidden", storage_class="static", linkage="internal"),
        )
    )
    harness = HarnessGenerator(model).generate()
    exposed_names = [fn.name for fn in harness.functions]
    assert exposed_names == ["alpha", "beta"]
    assert "/* exposes: int alpha(void) */" in harness.source
    assert "hidden" not in harness.source


def test_function_signature_rendered_with_parameters() -> None:
    """verifies: TOOL-HAR-020"""
    model = _single_unit_model(
        (
            _function(
                "scale",
                parameters=(
                    ParameterModel(name="value", type="ref:type.int"),
                    ParameterModel(name="factor", type="ref:type.int"),
                ),
            ),
        )
    )
    harness = HarnessGenerator(model).generate()
    assert "/* exposes: int scale(int value, int factor) */" in harness.source


def test_unresolvable_parameter_type_is_flagged_not_invented() -> None:
    """verifies: TOOL-HAR-020"""
    model = _single_unit_model(
        (
            _function(
                "weird",
                parameters=(ParameterModel(name="blob", type="ref:type.struct.Mystery"),),
            ),
        ),
        types={"type.int": _builtin("int")},
    )
    harness = HarnessGenerator(model).generate()
    assert "ectt:unresolved-type(ref:type.struct.Mystery) blob" in harness.source


def test_globals_recorded_with_merged_access() -> None:
    """verifies: TOOL-HAR-040"""
    model = _single_unit_model(
        (
            _function("reader", globals_=(GlobalAccessModel(name="g_count", access="r"),)),
            _function("writer", globals_=(GlobalAccessModel(name="g_count", access="w"),)),
            _function("reset", globals_=(GlobalAccessModel(name="g_count", access="rw"),)),
        )
    )
    harness = HarnessGenerator(model).generate()
    assert harness.variables == (ExposedVariable(name="g_count", access="rw"),)
    assert "/* ectt:exposes-global: g_count rw */" in harness.source


def test_globals_sorted_and_read_only_recorded() -> None:
    """verifies: TOOL-HAR-040"""
    model = _single_unit_model(
        (
            _function("one", globals_=(GlobalAccessModel(name="g_zeta", access="r"),)),
            _function("two", globals_=(GlobalAccessModel(name="g_alpha", access="rw"),)),
        )
    )
    harness = HarnessGenerator(model).generate()
    assert [v.name for v in harness.variables] == ["g_alpha", "g_zeta"]
    assert "/* ectt:exposes-global: g_zeta r */" in harness.source


def test_setup_and_teardown_hooks_present() -> None:
    """verifies: TOOL-HAR-050"""
    model = _single_unit_model((_function("compute"),))
    harness = HarnessGenerator(model).generate()
    assert harness.has_setup_teardown()
    for name in (
        "void ectt_register_setup(void (*fn)(void))",
        "void ectt_register_teardown(void (*fn)(void))",
        "void ectt_run_setup(void)",
        "void ectt_run_teardown(void)",
    ):
        assert name in harness.source


def test_generation_is_byte_identical_across_runs() -> None:
    """verifies: TOOL-HAR-010"""
    model = _single_unit_model(
        (
            _function("compute"),
            _function("helper", globals_=(GlobalAccessModel(name="g_state", access="w"),)),
        )
    )
    first = HarnessGenerator(model).generate().source
    second = HarnessGenerator(model).generate().source
    assert first == second


def test_empty_model_is_named_error() -> None:
    """verifies: TOOL-HAR-010"""
    with pytest.raises(NoUnitError):
        HarnessGenerator(_model(())).generate()


def test_multiple_units_without_designation_is_named_error() -> None:
    """verifies: TOOL-HAR-010"""
    units = (
        AnalysisUnit(path="a.c", status="parsed"),
        AnalysisUnit(path="b.c", status="parsed"),
    )
    with pytest.raises(AmbiguousUnitError) as excinfo:
        HarnessGenerator(_model(units)).generate()
    assert "a.c" in str(excinfo.value) and "b.c" in str(excinfo.value)


def test_designated_uut_selects_from_multiple_units() -> None:
    """verifies: TOOL-HAR-010"""
    units = (
        AnalysisUnit(path="a.c", status="parsed", functions=(_function("from_a"),)),
        AnalysisUnit(path="b.c", status="parsed", functions=(_function("from_b"),)),
    )
    harness = HarnessGenerator(_model(units), uut_path="b.c").generate()
    assert harness.uut_path == "b.c"
    assert [fn.name for fn in harness.functions] == ["from_b"]


def test_unknown_designated_uut_is_named_error() -> None:
    """verifies: TOOL-HAR-010"""
    model = _single_unit_model((_function("compute"),))
    with pytest.raises(UnknownUnitError):
        HarnessGenerator(model, uut_path="nope.c").generate()


def test_failed_unit_is_named_error() -> None:
    """verifies: TOOL-HAR-010"""
    model = _single_unit_model((), status="failed", path="broken.c")
    with pytest.raises(UnitNotParsedError):
        HarnessGenerator(model).generate()
