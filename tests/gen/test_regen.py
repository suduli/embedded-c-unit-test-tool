"""Tests for the WP-GEN-04 regeneration contract.

Covers: fingerprinted headers, byte-for-byte user-region preservation,
conflict reporting that writes nothing, harness and test-case staleness.

Verifies: TOOL-HAR-090, TOOL-HAR-100, TOOL-HAR-110, TOOL-CBT-070.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from ectt.ana.model import (
    AnalysisModel,
    AnalysisUnit,
    FunctionModel,
    ParameterModel,
    ProvenanceModel,
    SourceLocation,
    TypeModel,
)
from ectt.gen import (
    STATUS_CONFLICT,
    STATUS_PRESERVED,
    HarnessGenerator,
    HarnessRegenerationConflictError,
    HarnessStaleness,
    apply_regeneration,
    check_harness_staleness,
    check_test_case_staleness,
    regenerate,
)
from ectt.gen.regen import TestInterfaceBinding as InterfaceBinding


def _model(
    functions: tuple[FunctionModel, ...],
    *,
    version: str = "0.1.0",
) -> AnalysisModel:
    return AnalysisModel(
        provenance=ProvenanceModel(
            tool_version=version,
            front_end="fixture",
            generated_at="2026-11-18T00:00:00Z",
        ),
        units=(
            AnalysisUnit(
                path="uut.c",
                status="parsed",
                functions=functions,
            ),
        ),
        types={"type.int": TypeModel(kind="builtin", name="int")},
    )


def _fn(name: str, params: tuple[ParameterModel, ...] = ()) -> FunctionModel:
    return FunctionModel(
        name=name,
        linkage="external",
        storage_class="none",
        location=SourceLocation(file="uut.c", line=1),
        return_type="ref:type.int",
        parameters=params,
    )


def test_header_identifies_generated_version_and_model() -> None:
    """verifies: TOOL-HAR-090"""
    harness = HarnessGenerator(
        _model((_fn("compute"),)), tool_version="0.2.7"
    ).generate()
    assert "Generated by ectt" in harness.source
    assert "Tool version: 0.2.7" in harness.source
    assert "Source model UUT: uut.h" in harness.source
    assert harness.interface_fingerprint


def test_rendering_is_byte_identical_for_identical_input() -> None:
    """verifies: TOOL-HAR-090"""
    first = HarnessGenerator(_model((_fn("compute"),))).generate()
    second = HarnessGenerator(_model((_fn("compute"),))).generate()
    assert first.source == second.source


def test_regeneration_preserves_user_regions_byte_for_byte() -> None:
    """verifies: TOOL-HAR-100"""
    harness = HarnessGenerator(_model((_fn("compute"),))).generate()
    old_text = harness.source.replace(
        "/* ectt:user-region: test-cases begin */",
        "/* ectt:user-region: test-cases begin */\nvoid my_own_test(void) { compute(0); }\n",
    )
    result = regenerate(
        old_text, HarnessGenerator(_model((_fn("compute"),))).generate()
    )
    assert result.status == STATUS_PRESERVED
    assert result.written_anything
    assert "void my_own_test(void) { compute(0); }\n" in result.text
    # Byte-for-byte: the preserved text equals the old text.
    assert result.text == old_text


def test_conflicting_regeneration_reports_and_writes_nothing(tmp_path: Path) -> None:
    """verifies: TOOL-HAR-100"""
    old = HarnessGenerator(_model((_fn("compute"),))).generate()
    changed = HarnessGenerator(
        _model((_fn("compute", (ParameterModel(name="x", type="ref:type.int"),)),))
    ).generate()
    target = tmp_path / "uut.harness.c"
    target.write_text(old.source, encoding="utf-8")
    result = regenerate(old.source, changed)
    assert result.status == STATUS_CONFLICT
    assert result.text is None
    assert any("compute" in conflict for conflict in result.conflicts)
    with pytest.raises(HarnessRegenerationConflictError) as excinfo:
        apply_regeneration(target, result)
    assert "compute" in str(excinfo.value)
    # Nothing was written: the file still carries the old text byte-for-byte.
    assert target.read_text(encoding="utf-8") == old.source


def test_conflict_reports_removed_and_added_signatures() -> None:
    """verifies: TOOL-HAR-100"""
    old = HarnessGenerator(_model((_fn("alpha"), _fn("beta")))).generate()
    new = HarnessGenerator(_model((_fn("alpha"), _fn("gamma")))).generate()
    result = regenerate(old.source, new)
    joined = "; ".join(result.conflicts)
    assert "removed" in joined and "beta" in joined
    assert "added" in joined and "gamma" in joined


def test_harness_staleness_detected_by_fingerprint() -> None:
    """verifies: TOOL-HAR-110"""
    old = HarnessGenerator(_model((_fn("compute"),))).generate()
    changed = HarnessGenerator(
        _model((_fn("compute", (ParameterModel(name="x", type="ref:type.int"),)),))
    ).generate()
    verdict = check_harness_staleness(old.source, changed)
    assert isinstance(verdict, HarnessStaleness)
    assert verdict.stale is True
    fresh = check_harness_staleness(
        old.source, HarnessGenerator(_model((_fn("compute"),))).generate()
    )
    assert fresh.stale is False
    assert fresh.reasons == ()


def test_harness_without_fingerprint_is_stale() -> None:
    """verifies: TOOL-HAR-110"""
    harness = HarnessGenerator(_model((_fn("compute"),))).generate()
    verdict = check_harness_staleness("/* some old hand-made harness */", harness)
    assert verdict.stale is True
    assert "no interface fingerprint" in verdict.reasons[0]


def test_test_case_staleness_detected_by_fingerprint() -> None:
    """verifies: TOOL-CBT-070"""
    harness = HarnessGenerator(_model((_fn("compute"),))).generate()
    binding = InterfaceBinding(
        case_id="case_add", interface_fingerprint=harness.interface_fingerprint
    )
    assert check_test_case_staleness(binding, harness).stale is False
    changed = HarnessGenerator(
        _model((_fn("compute", (ParameterModel(name="x", type="ref:type.int"),)),))
    ).generate()
    verdict = check_test_case_staleness(binding, changed)
    assert verdict.stale is True
    assert "interface fingerprint changed" in verdict.reasons[0]


def test_apply_writes_preserved_result(tmp_path: Path) -> None:
    """verifies: TOOL-HAR-100"""
    harness = HarnessGenerator(_model((_fn("compute"),))).generate()
    result = regenerate(harness.source, harness)
    target = tmp_path / "out.c"
    apply_regeneration(target, result)
    assert target.read_text(encoding="utf-8") == harness.source


def test_user_region_without_a_slot_in_regenerated_source_is_a_conflict() -> None:
    """verifies: TOOL-HAR-100

    A user region whose slot is missing from the regenerated source must not be
    dropped silently: the regeneration is refused and nothing is written.
    """
    harness = HarnessGenerator(_model((_fn("compute"),))).generate()
    old_text = (
        harness.source
        + "\n/* ectt:user-region: legacy-hook begin */\nuser_code_kept;\n"
        + "/* ectt:user-region: legacy-hook end */\n"
    )
    result = regenerate(
        old_text, HarnessGenerator(_model((_fn("compute"),))).generate()
    )
    assert result.status == STATUS_CONFLICT
    assert result.text is None
    assert not result.written_anything
    assert "user region dropped: legacy-hook" in result.conflicts
