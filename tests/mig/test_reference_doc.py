"""The shipped interchange-format reference matches the generator (B5).

docs/reference/interchange-format.md is generated by
docs/reference/generate_interchange_reference.py from the format registry;
this test fails when the committed document drifts from
:func:`ectt.mig.formats.render_format_reference`.
"""

from __future__ import annotations

from pathlib import Path

from ectt.mig.formats import render_format_reference

REPO_ROOT = Path(__file__).parents[2]
REFERENCE = REPO_ROOT / "docs" / "reference" / "interchange-format.md"
GENERATOR = REPO_ROOT / "docs" / "reference" / "generate_interchange_reference.py"


def test_shipped_reference_matches_the_generator() -> None:
    assert REFERENCE.is_file()
    assert REFERENCE.read_text(encoding="utf-8") == render_format_reference()


def test_generator_script_exists_and_targets_the_reference() -> None:
    assert GENERATOR.is_file()
    source = GENERATOR.read_text(encoding="utf-8")
    assert "render_format_reference" in source
    assert "interchange-format.md" in source


def test_reference_documents_the_current_analysis_model_version() -> None:
    from ectt.ana.persist import SCHEMA_VERSION_CURRENT

    text = REFERENCE.read_text(encoding="utf-8")
    assert f"| `analysis-model` | both | json | {SCHEMA_VERSION_CURRENT} |" in text
